const SYSTEM_ERROR_FROM = 90000

export function describeError(result, status) {
  const template = ERROR_MESSAGES[result?.code] ?? `請求失敗（${status}）`
  const text = template.replace(/\{(\w+)\}/g, (_, key) => result?.data?.[key] ?? '')
  // 附追查編號
  const showId = result?.requestId && result.code >= SYSTEM_ERROR_FROM
  return showId ? `${text}（錯誤編號 ${result.requestId}）` : text
}
